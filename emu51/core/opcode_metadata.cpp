constexpr bool validMetadata() {
    std::array<bool, 256> orders{};
    for (std::size_t i = 0; i < kOpcodes.size(); ++i) {
        const auto& op = kOpcodes[i];
        if (op.code != i || op.lenght < 1 || op.lenght > 3 ||
            op.cycles < 1 || op.cycles > 4 || op.mnem[0] == '\0' ||
            op.assemblyOrder > 255 || orders[op.assemblyOrder]) return false;
        orders[op.assemblyOrder] = true;
        if ((i == 0xa5) != (op.assemblyOrder == 255)) return false;
    }
    return true;
}
static_assert(validMetadata(), "Invalid 8051 opcode metadata");
